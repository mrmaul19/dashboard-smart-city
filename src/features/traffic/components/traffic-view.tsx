'use client';

import { useMemo } from 'react';
import { AlertTriangle, Car, Gauge, Route } from 'lucide-react';
import { Panel, PanelHeader } from '@/components/ui/panel';
import { ProvenanceBadge } from '@/components/ui/provenance-badge';
import { StatTile } from '@/components/ui/stat-tile';
import { LoadingState } from '@/components/ui/states';
import { useCityManifest, useCityTiles } from '@/features/city/hooks/use-city-data';
import { SOURCE_OSM, SOURCE_SIMULATION } from '@/lib/constants/data-sources';
import { formatInteger, formatNumber } from '@/lib/utils/format';
import { realValue, simulatedValue } from '@/types/data-envelope';
import { useCityStore } from '@/stores/city-store';
import { buildRoadGraph } from '../simulation/road-graph';
import {
  TrafficSimulation,
  VEHICLE_TYPES,
} from '../simulation/traffic-sim';

/**
 * Traffic view.
 *
 * Every number on this page is SIMULATED except the road network it runs on.
 * The page says so once, prominently, and each tile carries its own badge —
 * the spec requires simulated traffic to be clearly identified, and a single
 * footnote is too easy to miss.
 *
 * The vehicle counts here are computed from the same graph and the same
 * deterministic simulation the 3D scene uses, so the figures match what is on
 * screen rather than being a second, independent estimate.
 */
export function TrafficView() {
  const cityId = useCityStore((s) => s.cityId);
  const density = useCityStore((s) => s.trafficDensity);
  const setTrafficDensity = useCityStore((s) => s.setTrafficDensity);

  const { data: manifest } = useCityManifest(cityId);
  const { tiles, isLoading } = useCityTiles(cityId, manifest);

  const graph = useMemo(
    () => buildRoadGraph(tiles.flatMap((tile) => tile.roads)),
    [tiles],
  );

  const summary = useMemo(() => {
    if (graph.edges.length === 0) return null;

    const simulation = new TrafficSimulation(graph);
    const vehicles = simulation.targetCount(density);

    // Class mix of the real network, which is what makes the simulated speeds
    // differ from road to road.
    const byClass = new Map<string, number>();
    for (const edge of graph.edges) {
      byClass.set(
        edge.roadClass,
        (byClass.get(edge.roadClass) ?? 0) + edge.lengthM,
      );
    }

    return {
      vehicles,
      byClass: [...byClass.entries()].sort((a, b) => b[1] - a[1]),
      onewayShare:
        graph.edges.filter((edge) => edge.oneway).length / graph.edges.length,
      junctions: graph.nodeCount,
    };
  }, [graph, density]);

  if (isLoading || !summary) {
    return <LoadingState label="Building the road graph" />;
  }

  return (
    <div className="h-full space-y-3 overflow-y-auto p-3">
      <Panel>
        <div className="flex items-start gap-2">
          <ProvenanceBadge provenance="SIMULATED" size="md" />
          <p className="text-xs leading-relaxed text-muted">
            <span className="font-medium text-fg">
              This traffic is generated by the application.
            </span>{' '}
            No free, open, real-time congestion feed exists for Jakarta —
            TomTom, HERE and Google traffic are paid and licence-restricted, and
            OpenStreetMap carries no congestion data. Vehicle positions, speeds
            and congestion levels below are simulated. The road network they run
            on is real OpenStreetMap data.
          </p>
        </div>
      </Panel>

      <Panel flush>
        <PanelHeader title="Simulation" subtitle="adjust density to see congestion form" />
        <div className="space-y-4 p-3">
          <div>
            <label
              htmlFor="traffic-density"
              className="mb-1.5 flex items-baseline justify-between gap-2"
            >
              <span className="text-xs text-muted">Traffic density</span>
              <span className="readout text-xs text-fg">
                {Math.round(density * 100)}%
              </span>
            </label>
            <input
              id="traffic-density"
              type="range"
              min={0}
              max={100}
              step={5}
              value={Math.round(density * 100)}
              onChange={(event) =>
                setTrafficDensity(Number(event.target.value) / 100)
              }
              className="w-full accent-[var(--app-accent)]"
              aria-describedby="traffic-density-hint"
            />
            <p id="traffic-density-hint" className="mt-1 text-[11px] text-dim">
              {formatInteger(summary.vehicles)} vehicles over{' '}
              {formatNumber(graph.totalLengthM / 1000, 1)} km of road.
            </p>
          </div>

          <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
            <StatTile
              label="Vehicles simulated"
              envelope={simulatedValue<number>({
                value: summary.vehicles,
                source: SOURCE_SIMULATION,
              })}
              icon={Car}
              format={(value) => formatInteger(value)}
            />
            <StatTile
              label="Road network"
              envelope={realValue<number>({
                value: graph.totalLengthM / 1000,
                source: SOURCE_OSM,
                unit: 'km',
                measuredAt: manifest?.generatedAt ?? null,
              })}
              icon={Route}
              format={(value) => formatNumber(value, 1)}
            />
            <StatTile
              label="Drivable segments"
              envelope={realValue<number>({
                value: graph.edges.length,
                source: SOURCE_OSM,
                measuredAt: manifest?.generatedAt ?? null,
                note: 'Ways split at shared junctions',
              })}
              icon={Route}
              format={(value) => formatInteger(value)}
            />
            <StatTile
              label="Junctions"
              envelope={realValue<number>({
                value: summary.junctions,
                source: SOURCE_OSM,
                measuredAt: manifest?.generatedAt ?? null,
              })}
              icon={Gauge}
              format={(value) => formatInteger(value)}
            />
          </div>
        </div>
      </Panel>

      <div className="grid grid-cols-1 gap-3 xl:grid-cols-2">
        <Panel flush>
          <PanelHeader
            title="Fleet mix"
            subtitle="assumed proportions"
            actions={<ProvenanceBadge provenance="SIMULATED" />}
          />
          <table className="w-full text-[11px]">
            <thead>
              <tr className="border-b border-border-subtle">
                <th scope="col" className="panel-heading p-2 text-left">Type</th>
                <th scope="col" className="panel-heading p-2 text-right">Share</th>
                <th scope="col" className="panel-heading p-2 text-right">Count</th>
                <th scope="col" className="panel-heading p-2 text-right">Speed</th>
              </tr>
            </thead>
            <tbody>
              {VEHICLE_TYPES.map((spec) => (
                <tr key={spec.type} className="border-b border-border-subtle/60">
                  <td className="p-2">
                    <span className="flex items-center gap-1.5">
                      <span
                        className="size-2 rounded-sm"
                        style={{ backgroundColor: spec.colour }}
                        aria-hidden="true"
                      />
                      <span className="text-muted">{spec.label}</span>
                    </span>
                  </td>
                  <td className="readout p-2 text-right text-muted">
                    {Math.round(spec.share * 100)}%
                  </td>
                  <td className="readout p-2 text-right text-muted">
                    {formatInteger(Math.round(summary.vehicles * spec.share))}
                  </td>
                  <td className="readout p-2 text-right text-dim">
                    ×{spec.speedFactor.toFixed(2)}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
          <p className="p-3 pt-2 text-[11px] leading-snug text-dim">
            Motorcycle-dominant, which is what Jakarta&rsquo;s traffic looks
            like. The proportions are a plausible assumption, not a measured
            statistic.
          </p>
        </Panel>

        <Panel flush>
          <PanelHeader
            title="Road network by class"
            subtitle="real OpenStreetMap data"
            actions={<ProvenanceBadge provenance="REAL" />}
          />
          <table className="w-full text-[11px]">
            <thead>
              <tr className="border-b border-border-subtle">
                <th scope="col" className="panel-heading p-2 text-left">Class</th>
                <th scope="col" className="panel-heading p-2 text-right">Length</th>
                <th scope="col" className="panel-heading p-2 text-right">Share</th>
              </tr>
            </thead>
            <tbody>
              {summary.byClass.map(([roadClass, length]) => (
                <tr key={roadClass} className="border-b border-border-subtle/60">
                  <td className="p-2 text-muted">{roadClass}</td>
                  <td className="readout p-2 text-right text-muted">
                    {formatNumber(length / 1000, 2)} km
                  </td>
                  <td className="readout p-2 text-right text-dim">
                    {Math.round((length / graph.totalLengthM) * 100)}%
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
          <p className="p-3 pt-2 text-[11px] text-dim">
            {Math.round(summary.onewayShare * 100)}% of segments are one-way,
            which the simulation respects when choosing turns.
          </p>
        </Panel>
      </div>

      <Panel>
        <p className="flex items-start gap-2 text-[11px] leading-snug text-muted">
          <AlertTriangle
            className="mt-0.5 size-3.5 shrink-0 text-sim"
            aria-hidden="true"
          />
          <span>
            Congestion colours in the 3D view are emergent, not scripted:
            vehicles slow where they are dense, which makes them denser still.
            Green is free-flowing, amber is building, red is saturated against
            the segment&rsquo;s estimated capacity. The underlying road geometry,
            classification, lane counts and one-way restrictions are all real.
          </span>
        </p>
      </Panel>
    </div>
  );
}
